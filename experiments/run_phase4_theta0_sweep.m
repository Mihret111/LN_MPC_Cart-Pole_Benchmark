function out = run_phase4lite_theta0_sweep()
% Fast ROA-proxy: 1D sweep over theta0 with thetadot0 = 0
% Outputs figures + LaTeX table

cfg0 = default_config();
cfg0.Ts = 0.02;
cfg0.Np = 20;

root = setup_paths();
figDir = fullfile(root,'figures');
% 
% exportgraphics(gcf, fullfile(figDir, "F07_success_vs_theta0.png"), 'Resolution', 250);
% exportgraphics(gcf, fullfile(figDir, "F11_Jcl_vs_Np.png"), 'Resolution', 250);

% Keep runs short for sweep (enough to settle)
cfg0.N_steps = 200;   % 4 seconds at 20ms

theta0_list = [0.02 0.04 0.06 0.08 0.10 0.12 0.14 0.16 0.18 0.20 0.22 0.24 0.26 0.28 0.30];

controllers = ["lqr", "linear_mpc","casadi_nmpc"];
labels = ["LQR", "LMPC","CasADi NMPC"];

% Ensure folders
if ~exist("figures","dir"), mkdir("figures"); end
if ~exist(fullfile("paper","tables"),"dir"), mkdir(fullfile("paper","tables")); end

rows = [];
k = 0;

for c = 1:numel(controllers)
    cfg = cfg0;
    cfg.controller.type = controllers(c);

    for th0 = theta0_list
        x0 = [0; 0; th0; 0];   % p0=0, pdot0=0, thetadot0=0
        cfg.x0 = x0;

        res = run_experiment(cfg);

        % Classify success using practical criteria
        cls = classify_success_1d(res);

        k = k + 1;
        rows(k).controller = char(labels(c));
        rows(k).theta0 = th0;
        rows(k).success = cls.success;
        rows(k).reason = char(cls.reason);

        rows(k).theta_settle_s = res.metrics.theta_settle_s;
        rows(k).theta_rms = res.metrics.theta_rms;
        rows(k).p_rms = res.metrics.p_rms;

        rows(k).solve_p95_ms = res.metrics.solve_p95_ms;
        rows(k).solve_max_ms = res.metrics.solve_max_ms;
    end
end

T = struct2table(rows);

% --- Compute critical theta0 (max theta0 with success) ---
crit = struct();
for c = 1:numel(labels)
    mask = strcmp(T.controller, labels(c));
    sub = T(mask,:);
    ok = sub.theta0(sub.success==1);
    if isempty(ok)
        crit.(matlab.lang.makeValidName(labels(c))) = NaN;
    else
        crit.(matlab.lang.makeValidName(labels(c))) = max(ok);
    end
end

% --- Plot 1: success vs theta0 ---
figure('Color','w'); hold on; grid on;
for c = 1:numel(labels)
    mask = strcmp(T.controller, labels(c));
    sub = T(mask,:);
    plot(sub.theta0, sub.success, '-o', 'LineWidth', 1.2);
end
xlabel('\theta_0 [rad]');
ylabel('success (1=yes, 0=no)');
title(' Stabilization success vs initial angle (\dot{\theta}_0=0)');
legend(labels,'Location','best');
exportgraphics(gcf, fullfile(figDir, "F07_success_vs_theta0.png"), 'Resolution', 250);

% --- Plot 2: p95 solve time vs theta0 ---
figure('Color','w'); hold on; grid on;
for c = 1:numel(labels)
    mask = strcmp(T.controller, labels(c));
    sub = T(mask,:);
    plot(sub.theta0, sub.solve_p95_ms, '-o', 'LineWidth', 1.2);
end
yline(20,'--','20 ms budget');
xlabel('\theta_0 [rad]');
ylabel('p95 solve time [ms]');
title(' Real-time feasibility vs initial angle');
legend(labels,'Location','best');
exportgraphics(gcf, fullfile(figDir, "F08_p95_vs_theta0.png"), 'Resolution', 250);

% --- Export LaTeX table ---
export_theta0_table_latex(T, crit, fullfile("paper","tables","T02_theta0_sweep.tex"));

% Return
out.table = T;
out.critical = crit;

disp("Phase 4-lite done:");
disp(" - figures/F07_success_vs_theta0.png");
disp(" - figures/F08_p95_vs_theta0.png");
disp(" - paper/tables/T02_theta0_sweep.tex");
disp("Critical theta0 (approx):");
disp(crit);

end

% -------- Success classifier for 1D sweep --------
function cls = classify_success_1d(res)
% Practical and forgiving: success if it settles reasonably and stays within constraints.
cfg = res.cfg; params = res.params; m = res.metrics;

dumax_step = params.dumax * cfg.Ts;

constraints_ok = ...
    (m.u_maxabs <= params.umax + 1e-6) && ...
    (m.du_step_maxabs <= dumax_step + 1e-6) && ...
    (m.p_maxabs <= params.pmax + 1e-6) && ...
    (m.theta_maxabs <= params.thetamax + 1e-6);

% Stabilized if settle time exists and is within simulation horizon
Tend = res.t(end);
stable = isfinite(m.theta_settle_s) && (m.theta_settle_s <= 0.95*Tend);

% Optional final error check (not too strict)
theta_final = abs(res.X(end,3));
stable = stable && (theta_final < 0.08);  % ~4.6 deg

cls = struct();
cls.success = constraints_ok && stable;
if ~constraints_ok
    cls.reason = "constraint_violation";
elseif ~stable
    cls.reason = "not_stabilized";
else
    cls.reason = "ok";
end
end

% -------- LaTeX export --------
function export_theta0_table_latex(T, crit, out_tex_path)
fid = fopen(out_tex_path,'w');
assert(fid>0, "Could not open %s", out_tex_path);

fprintf(fid, "%% Auto-generated by run_phase4lite_theta0_sweep.m\n");
fprintf(fid, "\\begin{table}[t]\\centering\n");
fprintf(fid, "\\caption{ stabilization boundary over initial angle ($\\dot\\theta_0=0$), $T_s=20$ ms, $N_p=20$.}\\label{tab:theta0sweep}\n");
fprintf(fid, "\\begin{tabular}{lcccccc}\\toprule\n");
fprintf(fid, "Controller & $\\theta_{0,\\max}$ & succ. rate & $t_s$ (median) & $\\theta_{\\mathrm{rms}}$ (median) & p95 (median) [ms] & max (median) [ms]\\\\\\midrule\n");

labels = unique(T.controller,'stable');
for i=1:numel(labels)
    mask = strcmp(T.controller, labels{i});
    sub = T(mask,:);

    theta_max = crit.(matlab.lang.makeValidName(labels{i}));
    succ_rate = mean(sub.success);

    ts_med = median(sub.theta_settle_s(sub.success==1), 'omitnan');
    th_rms_med = median(sub.theta_rms(sub.success==1), 'omitnan');
    p95_med = median(sub.solve_p95_ms(sub.success==1), 'omitnan');
    max_med = median(sub.solve_max_ms(sub.success==1), 'omitnan');

    fprintf(fid, "%s & %.2f & %.2f & %.2f & %.4f & %.2f & %.2f\\\\\n", ...
        labels{i}, theta_max, succ_rate, ts_med, th_rms_med, p95_med, max_med);
end

fprintf(fid, "\\bottomrule\\end{tabular}\\end{table}\n");
fclose(fid);
end
