cfg0.Ts = 0.02;

% fixed simulation window ~4s
cfg0.N_steps = 200;

Np_list = [10 15 20 30 40];

% Boundary sweep grid (keep small; we only need boundary trend)
theta_grid = 0.02:0.02:0.30;

controllers = ["linear_mpc","casadi_nmpc"];
labels = ["LMPC","CasADi NMPC"];

% Ensure folders
if ~exist("figures","dir"), mkdir("figures"); end
if ~exist(fullfile("paper","tables"),"dir"), mkdir(fullfile("paper","tables")); end

rows = [];
r = 0;

% Fixed baseline initial condition (moderate perturbation)
x0_baseline = [0;0;0.12;0];      % ≈ 6.8755°
 
for Np = Np_list
    for c = 1:numel(controllers)

        cfg = cfg0;
        cfg.Np = Np;
        cfg.controller.type = controllers(c);
        cfg.x0 = x0_baseline;

        % --- baseline run ---
        res = run_experiment(cfg);

        % compute closed-loop cost
        % Jcl = compute_closedloop_cost(res);

        % boundary search (stabilizable / deployable)
        % bnd = find_theta0_boundary(cfg0_withNp(cfg0,Np), controllers(c), theta_grid);

