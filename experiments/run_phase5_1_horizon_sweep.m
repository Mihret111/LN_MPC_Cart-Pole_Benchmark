        % rows(r).solve_max_ms = res.metrics.solve_max_ms;

        % rows(r).Jcl = Jcl;
        disp(rows)
        % boundaries
        % rows(r).theta0_stabilizable_max = bnd.theta_stabilizable_max;
        % rows(r).theta0_deployable_max = bnd.theta_deployable_max;
    end
end

T = struct2table(rows);
out.table = T;

% --- Plot F09: p95 solve time vs Np ---
figure('Color','w'); hold on; grid on;
for c = 1:numel(labels)
    mask = strcmp(T.controller, labels(c));
