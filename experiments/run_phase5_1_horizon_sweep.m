function cfg = cfg0_withNp(cfg0, Np)
cfg = cfg0;
cfg.Np = Np;
cfg.x0 = [0;0;0.1;0];
end

function export_horizon_table_latex(T, out_tex_path)
fid = fopen(out_tex_path,'w');
assert(fid>0, "Could not open %s", out_tex_path);

fprintf(fid, "%% Auto-generated by run_phase5_1_horizon_sweep.m\n");
fprintf(fid, "\\begin{table}[t]\\centering\n");
fprintf(fid, "\\caption{Phase 5.1 horizon sweep at $T_s=20$ ms (fixed $T_{sim}\\approx 4$s).}\\label{tab:horizonsweep}\n");
fprintf(fid, "\\begin{tabular}{lcccccccc}\\toprule\n");
fprintf(fid, "Controller & $N_p$ & p95 [ms] & max [ms] & $J_{cl}$ & $\\theta_{0,max}^{stab}$ & $\\theta_{0,max}^{rt}$ & $t_s$ [s] & $\\theta_{rms}$\\\\\\midrule\n");

for i=1:height(T)
    fprintf(fid, "%s & %d & %.2f & %.2f & %.3g & %.2f & %.2f & %.2f & %.4f\\\\\n", ...
        T.controller{i}, T.Np(i), T.solve_p95_ms(i), T.solve_max_ms(i), T.Jcl(i), ...
        T.theta0_stabilizable_max(i), T.theta0_deployable_max(i), ...
        T.theta_settle_s(i), T.theta_rms(i));
end

fprintf(fid, "\\bottomrule\\end{tabular}\\end{table}\n");
fclose(fid);
end
