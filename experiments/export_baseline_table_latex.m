function export_baseline_table_latex(results, labels, out_tex_path)
% Export a LaTeX booktabs table comparing controllers (baseline scenario).

rows = numel(results);
data = cell(rows, 9);

for i=1:rows
    r = results{i};
    m = r.metrics;

    data{i,1} = labels{i};
    data{i,2} = sprintf('%.2f', m.theta_rms);
    data{i,3} = sprintf('%.3f', m.theta_maxabs);
    data{i,4} = sprintf('%.2f', m.theta_settle_s);
    data{i,5} = sprintf('%.2f', m.p_rms);
    data{i,6} = sprintf('%.3f', m.p_maxabs);
    data{i,7} = sprintf('%.2f', m.solve_avg_ms);
    data{i,8} = sprintf('%.2f', m.solve_p95_ms);
    data{i,9} = sprintf('%.2f', m.solve_max_ms);
end

fid = fopen(out_tex_path,'w');
assert(fid>0, "Could not open output file: %s", out_tex_path);

fprintf(fid, "%% Auto-generated by export_baseline_table_latex.m\n");
fprintf(fid, "\\begin{table}[t]\n\\centering\n");
fprintf(fid, "\\caption{Baseline comparison (same scenario).}\\label{tab:baseline}\n");
fprintf(fid, "\\begin{tabular}{lcccccccc}\n");
fprintf(fid, "\\toprule\n");
fprintf(fid, "Controller & $\\theta_{\\mathrm{rms}}$ & $|\\theta|_{\\max}$ & $t_s$ & $p_{\\mathrm{rms}}$ & $|p|_{\\max}$ & avg [ms] & p95 [ms] & max [ms]\\\\\n");
fprintf(fid, "\\midrule\n");

for i=1:rows
    fprintf(fid, "%s & %s & %s & %s & %s & %s & %s & %s & %s\\\\\n", data{i,:});
end

fprintf(fid, "\\bottomrule\n\\end{tabular}\n\\end{table}\n");
fclose(fid);
end
