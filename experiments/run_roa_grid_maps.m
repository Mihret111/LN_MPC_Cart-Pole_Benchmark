function out = run_roa_grid_maps()
%RUN_ROA_GRID_MAPS
% Builds ROA-proxy maps for LMPC vs CasADi NMPC
% Outputs:
%   figures/F07_roa_LMPC.png
%   figures/F08_roa_CasadiNMPC.png
%   paper/tables/T02_roa_summary.tex

cfg0 = default_config();
cfg0.Ts = 0.02;
cfg0.Np = 20;

% --- Grid definition (start modest; enlarge later) ---
theta0_grid = linspace(-0.25, 0.25, 11);       % rad
thetadot0_grid = linspace(-1.5, 1.5, 11);      % rad/s

% controllers = ["linear_mpc", "casadi_nmpc"];
% labels = ["LMPC", "CasADi NMPC"];
controllers = ["casadi_nmpc"];
labels = ["CasADi NMPC"];

% allocate
Z = cell(numel(controllers),1);  % each is (num_theta x num_thetadot)
stats = struct();

for c = 1:numel(controllers)
    Z{c} = zeros(numel(theta0_grid), numel(thetadot0_grid));
    stats(c).label = char(labels(c));
    stats(c).n_total = numel(theta0_grid) * numel(thetadot0_grid);
    stats(c).n_fail = 0;
    stats(c).n_stable_not_rt = 0;
    stats(c).n_deployable = 0;
end

% Ensure folders
if ~exist("figures","dir"), mkdir("figures"); end
if ~exist(fullfile("paper","tables"),"dir"), mkdir(fullfile("paper","tables")); end

% --- Main sweep ---
for c = 1:numel(controllers)
    cfg = cfg0;
    cfg.controller.type = controllers(c);

    for i = 1:numel(theta0_grid)
        for j = 1:numel(thetadot0_grid)

            th0 = theta0_grid(i);
            thd0 = thetadot0_grid(j);

            x0 = [0; 0; th0; thd0];
            cfg = set_x0(cfg, x0);

            res = run_experiment(cfg);

            cls = classify_run_success_v2(res);
            Z{c}(i,j) = cls.code;

            % stats
            if cls.code == 0
                stats(c).n_fail = stats(c).n_fail + 1;
            elseif cls.code == 1
                stats(c).n_stable_not_rt = stats(c).n_stable_not_rt + 1;
            else
                stats(c).n_deployable = stats(c).n_deployable + 1;
            end
        end
    end


    root = setup_paths();
    figDir = fullfile(root,'figures');
    % fn = fullfile(figDir, base + "F07_roa_LMPC.png");

    % exportgraphics(gcf, savepath, 'Resolution', 250);

    % plot for controller
    fname = "";
    if controllers(c) == "linear_mpc"
        % fname = "figures/F07_roa_LMPC.png";
        fname = fullfile(figDir, "F07_roa_LMPC.png");
    else
        % fname = "figures/F08_roa_CasadiNMPC.png";
        fname = fullfile(figDir, "F08_roa_CasadiNMPC.png");
    end

    plot_roa_map(theta0_grid, thetadot0_grid, Z{c}, ...
        sprintf('ROA-proxy: %s (0 fail, 1 stable not RT, 2 stable+RT)', labels(c)), ...
        fname);
end

% --- Export summary table to LaTeX ---
export_roa_table_latex(stats, fullfile("paper","tables","T02_roa_summary.tex"));

% return
out.theta0_grid = theta0_grid;
out.thetadot0_grid = thetadot0_grid;
out.Z = Z;
out.stats = stats;

disp("Phase 4 ROA-proxy maps generated:");
disp(" - figures/F07_roa_LMPC.png");
disp(" - figures/F08_roa_CasadiNMPC.png");
disp(" - paper/tables/T02_roa_summary.tex");

end

% -------- local helper: set cfg initial state --------
function cfg = set_x0(cfg, x0)
% try to respect any existing convention; otherwise add cfg.x0
cfg.x0 = x0;
end

% -------- local helper: export LaTeX table --------
function export_roa_table_latex(stats, out_tex_path)

fid = fopen(out_tex_path,'w');
assert(fid>0, "Could not open output file: %s", out_tex_path);

fprintf(fid, "%% Auto-generated by run_roa_grid_maps.m\n");
fprintf(fid, "\\begin{table}[t]\n\\centering\n");
fprintf(fid, "\\caption{ROA-proxy grid summary (stabilizable vs deployable).}\\label{tab:roa}\n");
fprintf(fid, "\\begin{tabular}{lcccc}\n");
fprintf(fid, "\\toprule\n");
fprintf(fid, "Controller & Total & Fail & Stable (not RT) & Stable+RT\\\\\n");
fprintf(fid, "\\midrule\n");

for k=1:numel(stats)
    fprintf(fid, "%s & %d & %d & %d & %d\\\\\n", ...
        stats(k).label, stats(k).n_total, stats(k).n_fail, stats(k).n_stable_not_rt, stats(k).n_deployable);
end

fprintf(fid, "\\bottomrule\n\\end{tabular}\n\\end{table}\n");
fclose(fid);
end
