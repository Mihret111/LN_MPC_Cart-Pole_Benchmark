function make_phase7_2_summary_plots(T, figDir)

controllers = unique(T.controller,'stable');

if ~exist(fullfile("paper","tables"),"dir"), mkdir(fullfile("paper","tables")); end

% p95 vs A
figure('Color','w'); hold on; grid on;
for i=1:numel(controllers)
    Tc = T(strcmp(T.controller,controllers{i}),:);
    plot(Tc.A, Tc.solve_p95_ms, '-o');
end
yline(20,'--','Budget');
xlabel('Disturbance amplitude A [N]');
ylabel('solve time p95 [ms]');
legend(controllers,'Location','best');
title('p95 solve time vs force disturbance amplitude');
exportgraphics(gcf, fullfile(figDir,"F7_2_p95_vs_A.png"), 'Resolution', 250);

% theta maxabs vs A
figure('Color','w'); hold on; grid on;
for i=1:numel(controllers)
    Tc = T(strcmp(T.controller,controllers{i}),:);
    plot(Tc.A, Tc.theta_maxabs, '-o');
end
xlabel('Disturbance amplitude A [N]');
ylabel('max |\theta| [rad]');
legend(controllers,'Location','best');
title('Max |theta| vs force disturbance amplitude');
exportgraphics(gcf, fullfile(figDir,"F7_2_thetamax_vs_A.png"), 'Resolution', 250);


% --- Export LaTeX table ---
% export_horizon_table_latex(T, fullfile("paper","tables","T07_Disturbance_rejection.tex"));

end

